# String slicing
text = "Programming"
print("text =", text)

print("text[0:4]   =", text[0:4])     # Prog
print("text[6:-3]   =", text[6:-3])     # Prog
print("text[3:]    =", text[3:])      # gramming
print("text[:5]    =", text[:5])      # Progr
print("text[-4:]   =", text[-4:])     # ming
print("text[::3]   =", text[::3])     # Pormig
print("text[::-2]  =", text[::-2])    # reverse
print()
